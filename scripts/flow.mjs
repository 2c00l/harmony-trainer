// Drives the core loop in headless Chrome with a fake singing mic. Screens → artifacts/flow-*.png
import { chromium } from 'playwright';
import { resolve } from 'node:path';
const W = Number(process.env.W || 390), H = Number(process.env.H || 844);
const wav = resolve('artifacts/fake-voice.wav');
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', `--use-file-for-fake-audio-capture=${wav}`, '--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 2, permissions: ['microphone'] });
await ctx.addInitScript(() => { const s = JSON.parse(localStorage.getItem('ht.settings.v1') || '{}'); s.onboarded = true; localStorage.setItem('ht.settings.v1', JSON.stringify(s)); });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message + '\n' + e.stack));
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
const shot = (n) => page.screenshot({ path: `artifacts/flow-${n}.png` });
await page.goto('http://localhost:4190/#/');
await page.waitForTimeout(800);
await page.click('text=New harmony');
await page.waitForTimeout(1200);
await shot('1-empty');
await page.click('[aria-label="Record melody"]');
await page.waitForTimeout(9000);
await shot('2-recording');
await page.click('[aria-label="Stop recording"]');
await page.waitForTimeout(2500);
await shot('3-key');
await page.click('text=Looks right');
await page.waitForTimeout(800);
await shot('4-edit');
await page.click('.seg button[data-v=harmony]');
await page.waitForTimeout(800);
await shot('5-harmony');
// select a region by dragging on the roll
const box = await page.locator('canvas.roll').boundingBox();
await page.mouse.move(box.x + box.width * 0.55, box.y + box.height * 0.5);
await page.mouse.down();
await page.mouse.move(box.x + box.width * 0.85, box.y + box.height * 0.5, { steps: 8 });
await page.mouse.up();
await page.waitForTimeout(400);
await page.click('.chips .chip:has-text("3rd below")');
await page.waitForTimeout(600);
await shot('6-region');
await page.click('.seg button[data-v=sing]');
await page.waitForTimeout(600);
await page.click('[aria-label="Record harmony take"]');
await page.waitForTimeout(7000);
await shot('7-singing');
await page.click('[aria-label="Stop"]');
await page.waitForTimeout(2000);
await shot('8-summary');
const keep = page.locator('text=Keep as layer');
if (await keep.count()) { await keep.click(); await page.waitForTimeout(1500); }
await page.click('.seg button[data-v=mix]');
await page.waitForTimeout(800);
await shot('9-mix');
console.log(errs.length ? errs.join('\n') : 'no errors');
await browser.close();
